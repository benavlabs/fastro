def _git(root: Path, *arguments: str) -> None:
    subprocess.run(["git", "-C", str(root), *arguments], check=True, capture_output=True)


def _catalog(root: Path, old: str, new: str) -> None:
    catalog = root / "blueprint.toml"
    text = catalog.read_text()
    assert old in text
    catalog.write_text(text.replace(old, new))


def _append(root: Path, text: str) -> None:
    with (root / "blueprint.toml").open("a") as catalog:
        catalog.write(text)


def _features(root: Path, *names: str) -> None:
    toml = root / "fastro.toml"
    toml.write_text(FEATURES.sub(f"features = [{', '.join(map(repr, names))}]".replace("'", '"'), toml.read_text()))


def _track(root: Path, files: dict[str, bytes | str]) -> None:
    for name, data in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        if isinstance(data, str):
            (root / name).write_text(data)
        else:
            (root / name).write_bytes(data)
    _git(root, "add", *files)


