@pytest.mark.parametrize(
    ("flags", "terminal", "answer", "replaced"),
    [
        ([], False, "", False),
        (["--force"], False, "", True),
        (["-f"], False, "", True),
        (["--yes"], False, "", True),
        (["-y"], False, "", True),
        ([], True, "y\n", True),
        ([], True, "n\n", False),
    ],
)
def test_a_file_that_differs_is_replaced_only_once_the_user_confirms_or_with_force_or_yes(
    repo: Path, monkeypatch: pytest.MonkeyPatch, flags: list[str], terminal: bool, answer: str, replaced: bool
) -> None:
    (repo / "out").mkdir()
    (repo / "out" / "docker-compose.yml").write_text("mine\n")
    monkeypatch.setattr("fastro.commands.make._terminal", lambda: terminal)

    result = runner.invoke(cli.app, ["make", "deploy", "local", "-o", "out", *flags], input=answer)

    written = (repo / "out" / "docker-compose.yml").read_text()
    if replaced:
        said = "wrote out/docker-compose.yml"
    elif terminal:
        said = "kept out/docker-compose.yml"
    else:
        said = (
            "kept out/docker-compose.yml: it differs, and there's no terminal to ask on. Run again with --force to replace it."
        )
    assert result.exit_code == 0, result.output
    assert (written != "mine\n") is replaced
    assert result.stdout.splitlines()[-1] == said


def test_bool_and_str_params_reach_the_templates_and_take_either_spelling(repo: Path) -> None:
    _append(
        repo,
        '\n[generators.notes]\ntemplates = "blueprint/notes"\n'
        '[generators.notes.params.debug]\ntype = "bool"\ndefault = false\n'
        '[generators.notes.params.title]\ntype = "str"\ndefault = "none"\n',
    )
    _track(repo, {"blueprint/notes/notes.txt.j2": "{{ params.debug }} {{ params.title }}\n"})

    shown = []
    for flags in (["--debug", "--title", "a b"], ["--no-debug", "--title=c=d"], []):
        assert _make("notes", *flags, "--force").exit_code == 0
        shown.append((repo / "notes.txt").read_text())

    assert shown == ["True a b\n", "False c=d\n", "False none\n"]


