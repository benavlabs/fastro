@pytest.mark.parametrize("where", ["directory", "fifo", "symlink", "symlink-on-the-way", "file-on-the-way", "output-file"])
def test_an_output_path_make_cant_write_refuses_the_run_before_anything_is_written(
    repo: Path, tmp_path: Path, where: str
) -> None:
    out = repo / "out"
    out.mkdir()
    if where == "directory":
        (out / "docker-compose.yml").mkdir()
    if where == "fifo":
        os.mkfifo(out / "docker-compose.yml")
    if where == "symlink":
        (out / "docker-compose.yml").symlink_to(tmp_path / "elsewhere.yml")
    if where == "symlink-on-the-way":
        (tmp_path / "real").mkdir()
        (out / "nginx").symlink_to(tmp_path / "real")
    if where == "file-on-the-way":
        (out / "nginx").write_text("a file\n")
    if where == "output-file":
        out.rmdir()
        out.write_text("a file\n")
    message = {
        "directory": f"{out / 'docker-compose.yml'} isn't a regular file, so fastro make won't replace it.",
        "fifo": f"{out / 'docker-compose.yml'} isn't a regular file, so fastro make won't replace it.",
        "symlink": f"{out / 'docker-compose.yml'} is a symlink, and fastro make writes nothing through one.",
        "symlink-on-the-way": f"{out / 'nginx'} is a symlink, and fastro make writes nothing through one.",
        "file-on-the-way": f"{out / 'nginx'} isn't a directory, so fastro make can't write nginx/default.conf under it.",
        "output-file": f"{out} isn't a directory, so fastro make can't write in it.",
    }[where]

    result = _make("deploy", "nginx", "-o", "out")

    assert result.exit_code == 1, result.output
    assert result.stderr == f"error: {message}\n"
    assert not (tmp_path / "real" / "default.conf").exists()
    assert not (out / "docker-compose.yml").is_file() or where == "output-file"


