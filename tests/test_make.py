def test_a_dry_run_names_each_file_with_its_size_and_writes_nothing(repo: Path) -> None:
    (repo / "out" / "nginx").mkdir(parents=True)
    (repo / "out" / "nginx" / "default.conf").write_text("old\n")

    result = _make("deploy", "nginx", "-o", "out", "--dry-run")

    sizes = {path: len(data) for path, data in _files(LEGACY / "nginx-taskiq").items()}
    assert result.exit_code == 0, result.output
    assert result.stdout == (
        f"would write out/docker-compose.yml ({sizes['docker-compose.yml']} bytes)\n"
        f"would write out/nginx/default.conf ({sizes['nginx/default.conf']} bytes) (replacing what is there)\n"
    )
    assert _files(repo / "out") == {"nginx/default.conf": b"old\n"}


