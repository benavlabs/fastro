def test_a_wiring_key_that_breaks_its_rule_is_refused_at_its_line(body: str, problem: str) -> None:
    assert _problems(MINIMAL + body) == [f"blueprint.toml:{problem}"]


@pytest.mark.parametrize(
    ("body", "problem"),
    [
        (
            FILE.replace('"The app."', '\'Ends """ early\'') + RAW,
            "8: wiring[0].doc: can't contain '\"\"\"', which would end the docstring.",
        ),
        (
            '[wiring_defaults]\nheader = \'ends """ early\'\n',
            "7: wiring_defaults.header: can't contain '\"\"\"', which would end the docstring.",
        ),
        (FILE.replace('"The app."', "'Ends with \\'") + RAW, f"8: wiring[0].doc: {BACKSLASH}"),
        (FILE.replace('"The app."', "'Matches \\d+'") + RAW, f"8: wiring[0].doc: {BACKSLASH}"),
        (FILE.replace('"The app."', "'Says \"hi\"'") + RAW, f"8: wiring[0].doc: {QUOTE}"),
        (FILE.replace('"The app."', '"Says \\"hi\\"\\n\\n"') + RAW, f"8: wiring[0].doc: {QUOTE}"),
        (FILE + CLASS + "doc = 'Ends with \\'\n", f"13: wiring[0].slots[0].doc: {BACKSLASH}"),
        (FILE + CLASS + "doc = 'Says \"hi\"'\n", f"13: wiring[0].slots[0].doc: {QUOTE}"),
        ("[wiring_defaults]\nheader = 'C:\\fastro'\n", f"7: wiring_defaults.header: {BACKSLASH}"),
        ('[wiring_defaults]\nheader = "Run \\"fastro sync\\"\\n"\n', f"7: wiring_defaults.header: {QUOTE}"),
    ],
)
def test_text_that_goes_into_a_docstring_cant_end_it(body: str, problem: str) -> None:
    assert _problems(MINIMAL + body) == [f"blueprint.toml:{problem}"]


def test_header_lines_are_measured_after_leading_and_trailing_newlines_are_stripped() -> None:
    header = "\n" + "x" * 100 + "\n" + "y" * 100 + "\n\n"

    assert _load(MINIMAL + f'[wiring_defaults]\nheader = """\n{header}"""\n').header == header


def test_a_file_may_hold_several_raw_slots() -> None:
    assert len(_load(MINIMAL + FILE + RAW + RAW).wiring[0].slots) == 2


def test_a_long_header_line_is_numbered_from_the_first_line_with_text() -> None:
    text = MINIMAL + '[wiring_defaults]\nheader = """\n\n' + "x" * 101 + '\n"""\n'

    assert _problems(text) == [
        "blueprint.toml:7: wiring_defaults.header: line 1 is 101 characters long, and header lines are at most 100."
    ]
