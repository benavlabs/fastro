def _load(text: str) -> Blueprint:
    return load("blueprint.toml", text, Version("0.1.0"))


def _problems(text: str) -> list[str]:
    with pytest.raises(CatalogError) as caught:
        _load(text)
    return [str(problem) for problem in caught.value.problems]


def test_the_wiring_header_is_read() -> None:
    assert _load(MINIMAL + WIRED).header == (
        "Generated by fastro from blueprint.toml and fastro.toml. Don't edit: change\n"
        "fastro.toml (or [app] in it, for your own code) and run `fastro sync`.\n"
    )


def test_without_wiring_there_are_no_files_and_no_header() -> None:
    blueprint = _load(MINIMAL)

    assert (blueprint.wiring, blueprint.header) == ((), "")


def test_wiring_files_are_read_with_every_slot_kind() -> None:
    app, menu = _load(MINIMAL + WIRED).wiring
    slot = ("wiring", 0, "slots")

    assert app == Wiring(
        path=RepoPath("backend/src/wiring/app.py"),
        doc="The composition root.",
        condition=parse("accounts"),
        imports=("from fastapi import APIRouter", "import logging"),
        slots=(
            Slot(
                "tuple",
                "ROUTER_MOUNTS",
                "routers",
                annotation="tuple[RouterMount, ...]",
                item='RouterMount({name}, "{prefix}", throttled={throttled})',
                defaults={"throttled": True, "prefix": "", "weight": 1},
                item_imports=("from ..infrastructure.composition import RouterMount",),
                at=(*slot, 0),
            ),
            Slot("list", "TASK_MODULES", "task_modules", annotation="list[str]", literal=True, at=(*slot, 1)),
            Slot(
                "value",
                "EMAIL_SENDER",
                "email_sender",
                annotation="EmailSender | None",
                fallback="None",
                fallback_imports=("from crudauth import EmailSender",),
                at=(*slot, 2),
            ),
            Slot(
                "class",
                "Settings",
                "settings",
                fallback=Ref.parse("src.core.config:BaseSettings"),
                append=(Ref.parse("pydantic_settings:BaseSettings as Base"),),
                doc="Every feature's settings.",
                at=(*slot, 3),
            ),
            Slot(
                "reexport", "cached", "cache_decorator", fallback=Ref.parse("src.infrastructure.uncached:cached"), at=(*slot, 4)
            ),
            Slot("raw", code="settings = Settings()\n", at=(*slot, 5)),
        ),
        at=("wiring", 0),
    )
    assert menu == Wiring(
        path=RepoPath("frontend/src/wiring/menu.ts"),
        doc="The menu entries.",
        condition=None,
        imports=(),
        slots=(Slot("data", "MENU", "menu", format="ts", at=("wiring", 1, "slots", 0)),),
        at=("wiring", 1),
    )


def test_wiring_must_be_a_list_of_tables() -> None:
    assert _problems("wiring = 1\n" + MINIMAL) == ["blueprint.toml:1: wiring: should be a list of tables, not an integer."]


